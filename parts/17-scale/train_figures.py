"""
The Part XVII figures that require training.

    python3 train_figures.py

Everything here trains on a synthetic source whose entropy rate is computed in
closed form. That is the point: a scaling law's irreducible term E is supposed
to be the entropy of the data, and on real corpora nobody can check. Here we
can, so the fit has a right answer rather than a plausible one.

Three questions:

  * does a fitted power law recover the true entropy as its irreducible term?
  * does the learning-rate schedule error reproduce, and does it move the
    inferred compute-optimal allocation the way Chinchilla said it did?
  * what does a mixture-of-experts router actually do to load balance?
"""
